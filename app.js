// 3. 解析用户输入的性格代码 (例如: 30个字母)
function parseInput(inputStr) {
    const matches = inputStr.toUpperCase().match(/[A-C]/g);
    if (!matches || matches.length !== 30) {
        throw new Error('无效的性格代码，请确保包含 30 个 A/B/C 选项。');
    }
    return matches;
}

// 4. 将选项转换为 30 维向量
function getVector(answers) {
    return answers.map(ans => optionScores[ans]);
}

// 5. 计算两个向量之间的距离 (曼哈顿距离)
function calculateDistance(vec1, vec2) {
    let distance = 0;
    let exactMatches = 0;
    for (let i = 0; i < vec1.length; i++) {
        const diff = Math.abs(vec1[i] - vec2[i]);
        distance += diff;
        if (diff === 0) exactMatches++;
    }
    return { distance, exactMatches };
}

// 6. 匹配最接近的人格模板
function matchPersonality(userVector) {
    let bestMatch = null;
    let minDistance = Infinity;
    let maxExactMatches = -1;

    for (const template of personalityTemplates) {
        const { distance, exactMatches } = calculateDistance(userVector, template.vector);
        
        if (distance < minDistance || (distance === minDistance && exactMatches > maxExactMatches)) {
            minDistance = distance;
            maxExactMatches = exactMatches;
            bestMatch = template;
        }
    }

    return bestMatch;
}

// 7. 动态计算 5 字母代码和进度条百分比
function calculateDynamicTraits(userVector) {
    // 每个维度 6 题，总分范围 6-18 分。中位数是 12 分。
    let sumC = 0, sumA = 0, sumR = 0, sumT = 0, sumE = 0;
    for (let i = 0; i < 6; i++) sumC += userVector[i];
    for (let i = 6; i < 12; i++) sumA += userVector[i];
    for (let i = 12; i < 18; i++) sumR += userVector[i];
    for (let i = 18; i < 24; i++) sumT += userVector[i];
    for (let i = 24; i < 30; i++) sumE += userVector[i];

    // 计算百分比 (0% 偏左，100% 偏右)
    // 公式: ((score - 6) / 12) * 100
    const pctC = Math.round(((sumC - 6) / 12) * 100);
    const pctA = Math.round(((sumA - 6) / 12) * 100);
    const pctR = Math.round(((sumR - 6) / 12) * 100);
    const pctT = Math.round(((sumT - 6) / 12) * 100);
    const pctE = Math.round(((sumE - 6) / 12) * 100);

    // 确定 5 字母代码
    // C轴: S(Silent) vs C(Chatty)
    // A轴: O(Obedient) vs P(Proactive)
    // R轴: B(Bold) vs C(Cautious)
    // T轴: T(Thinker) vs D(Doer)
    // E轴: M(Machine) vs H(Human)
    const codeC = pctC >= 50 ? 'C' : 'S';
    const codeA = pctA >= 50 ? 'P' : 'O';
    const codeR = pctR >= 50 ? 'C' : 'B';
    const codeT = pctT >= 50 ? 'D' : 'T';
    const codeE = pctE >= 50 ? 'H' : 'M';

    const dynamicCode = `${codeC}-${codeA}-${codeR}-${codeT}-${codeE}`;

    return {
        dynamicCode,
        percentages: [pctC, pctA, pctR, pctT, pctE]
    };
}

// 8. 主流程函数 (供 UI 调用)
function runTest(inputStr) {
    try {
        const answers = parseInput(inputStr);
        const userVector = getVector(answers);
        
        const template = matchPersonality(userVector);
        const { dynamicCode, percentages } = calculateDynamicTraits(userVector);
        
        return { 
            success: true, 
            data: {
                template,
                dynamicCode,
                percentages
            } 
        };
    } catch (error) {
        return { success: false, error: error.message };
    }
}

